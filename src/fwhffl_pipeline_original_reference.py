"""
FWHFFL 2026 Draft Kit — Path B pipeline (Stages 1-6 + Validation Passes 1-8)
=============================================================================
Correctness-first implementation of DRAFT_KIT_FRAMEWORK.md v2.0.

Inputs (all real, all supplied by the owner):
  - FantasyPros_2026_Draft_ALL_Rankings.csv   : 2026 seasonal STAT projections
  - cheatsheet_2_.csv                         : 2026 market auction $ (12-team/$200, no-keeper anchor)
  - NFL_Offensive_Analytics_2024_2025.xlsx    : team environment + 2026 play-caller continuity
  - FWHFFL_2026_Auction_Database.xlsx         : measured league parameters (§2.1-2.6)
  - 2026_draft_results.csv (in /mnt/project)  : 2025 rosters + salaries -> keeper candidate pool
  - FantasyPros 2025 target/snap files        : Pass 4/5 usage validation

Design decisions locked with the owner:
  - Games assumption = OPTION A: trust FantasyPros' seasonal blend as-is.
    Season total / 17 is used ONLY to bin players into per-game shrink bands.
  - Stage 1 shrink = directional prior (ESCALATED: FantasyPros seasonal -> ESPN, not league-fitted).
  - Auction values are GENERATED by the model; the market sheet is the Stage 5 shape anchor
    and Stage 6 pre-keeper baseline, never a direct input.
  - Never manufacture projections. Never close a validation finding silently.
"""

import pandas as pd, numpy as np, re, json, sys

UPLOAD = "/mnt/user-data/uploads"
PROJECT = "/mnt/project"

# ----- measured league parameters (from FWHFFL_2026_Auction_Database.xlsx) -----
REPLACEMENT = {"QB": 18.98, "RB": 11.13, "WR": 9.15, "TE": 10.65}      # §2.1 pts/game
MAE         = {"QB": 6.67,  "RB": 6.54,  "WR": 6.34,  "TE": 5.84}      # §2.2 mean abs error
SHRINK_BANDS = [                                                        # §2.2 (per-game bins)
    (0, 5, 1.345), (5, 10, 0.960), (10, 15, 0.965), (15, 20, 0.954), (20, 999, 0.942)
]
# §2.4 open-auction tier inflation (projected-$ tiers)
TIER_INFLATION = [(40, 999, 0.396), (25, 40, 0.288), (15, 25, -0.117),
                  (8, 15, -0.391), (3, 8, -0.485), (1, 3, -0.129)]
POS_INFLATION  = {"RB": 0.167, "QB": -0.203, "WR": -0.117, "TE": -0.231}  # §2.4 by position
BUDGET, TEAMS, ROSTER = 2400, 12, 13
POOL_SIZE = TEAMS * ROSTER            # 156 priced spots
REG_WEIGHT_DEFAULT = 0.6              # §3.2 tunable regression toward mean for new play callers

FINDINGS = []  # (pass#, name, severity, disposition, detail)
def log(p, name, sev, disp, detail):
    FINDINGS.append((p, name, sev, disp, detail))

def norm(n):
    return re.sub(r"\s+(Jr\.|Sr\.|II|III|IV)$", "", str(n)).strip()

# =====================================================================
# DATA LOAD + POSITION MAP
# =====================================================================
def _num(x):
    try: return float(str(x).replace(",", "").strip())
    except: return np.nan

def load_projections():
    raw = pd.read_csv(f"{UPLOAD}/cheatsheet_2_.csv", header=1)
    market = {}
    for nc, vc in [("QB","VALUES.1"),("RB","VALUES.2"),("WR","VALUES.3"),("TE","VALUES.4")]:
        for _, r in raw.iterrows():
            nm = r[nc]
            if pd.isna(nm): continue
            m = re.match(r"^(.*?)\s*-\s*\w+$", str(nm))
            name = m.group(1).strip() if m else str(nm).strip()
            v = r[vc]
            if pd.notna(v) and str(v).strip() not in ("", "nan"):
                market[name] = float(str(v).replace("$", "").strip())

    # skill players (RB/WR/TE) with POS from the FLX file
    flx = pd.read_csv(f"{UPLOAD}/FantasyPros_Fantasy_Football_Projections_FLX.csv", header=0)
    flx.columns = ["Player","Team","POS","RuAtt","RuYd","RuTD","Rec","ReYd","ReTD","FL","FPTS"]
    flx = flx[flx.Player.astype(str).str.strip().str.len() > 1].copy()
    for c in ["RuAtt","RuYd","RuTD","Rec","ReYd","ReTD"]: flx[c] = flx[c].apply(_num)
    flx["Pos"] = flx.POS.str.extract(r"([A-Z]+)")
    flx["PaYd"] = 0.0; flx["PaTD"] = 0.0
    flx = flx.dropna(subset=["RuAtt","Rec"], how="all")

    # QBs from their own file
    qb = pd.read_csv(f"{UPLOAD}/FantasyPros_Fantasy_Football_Projections_QB_1_.csv", header=0)
    qb.columns = ["Player","Team","PaAtt","Cmp","PaYd","PaTD","INT","RuAtt","RuYd","RuTD","FL","FPTS"]
    qb = qb[qb.Player.astype(str).str.strip().str.len() > 1].copy()
    for c in ["PaYd","PaTD","RuAtt","RuYd","RuTD"]: qb[c] = qb[c].apply(_num)
    qb["Pos"] = "QB"; qb["Rec"] = 0.0; qb["ReYd"] = 0.0; qb["ReTD"] = 0.0

    cols = ["Player","Team","Pos","PaYd","PaTD","Rec","ReYd","ReTD","RuAtt","RuYd","RuTD"]
    off = pd.concat([flx[cols], qb[cols]], ignore_index=True)
    off = off[off.Pos.isin(["QB","RB","WR","TE"])].copy()
    off["SeasProj"] = (off.PaYd*.05 + off.PaTD*4 + off.RuYd*.15 + off.RuTD*6
                       + off.Rec*.5 + off.ReYd*.15 + off.ReTD*6)
    off["PG_raw"] = off.SeasProj / 17.0
    return off.reset_index(drop=True), market

# =====================================================================
# STAGE 1 — calibrate (shrink) + attach uncertainty band
# =====================================================================
def stage1(df):
    def shrink_for(pg):
        for lo, hi, s in SHRINK_BANDS:
            if lo <= pg < hi: return s
        return 1.0
    df = df.copy()
    df["shrink"] = df.PG_raw.apply(shrink_for)
    # never let the <5 inflation band touch real drafts (framework §2.2 caveat, n=80 artifact)
    df.loc[df.PG_raw < 5, "shrink"] = 1.0
    df["PG"] = df.PG_raw * df.shrink
    df["MAE"] = df.Pos.map(MAE)
    return df

# =====================================================================
# STAGE 2 — team environment (with double-count guard)
# =====================================================================
def stage2(df, reg_weight=REG_WEIGHT_DEFAULT, apply_weight=0.5):
    """apply_weight<1 because FantasyPros already prices coaching changes (double-count guard)."""
    wb = f"{UPLOAD}/NFL_Offensive_Analytics_2024_2025.xlsx"
    cm = pd.read_excel(wb, sheet_name="Coach Map", header=2).dropna(subset=["Team"])
    changed = set(cm.loc[cm["Play Caller Change 2026"].astype(str).str.upper()
                         .str.startswith("YES"), "Team"])
    aa = pd.read_excel(wb, sheet_name="Advanced Analytics", header=2).dropna(subset=["Team"])
    a25 = aa[aa.Season == 2025][["Team","Points/Game"]].copy()
    lg = a25["Points/Game"].mean()
    a25["mult_raw"] = a25["Points/Game"] / lg
    # regress new-play-caller teams toward league mean (1.0)
    a25["mult"] = a25.apply(
        lambda r: 1.0 + (r.mult_raw-1.0)*(1-reg_weight) if r.Team in changed else r.mult_raw, axis=1)
    # soften application (double-count guard)
    a25["mult_applied"] = 1.0 + (a25["mult"]-1.0)*apply_weight
    mult = dict(zip(a25.Team, a25.mult_applied))
    df = df.copy()
    df["env_mult"] = df.Team.map(mult).fillna(1.0)
    df["PG_env"] = df.PG * df.env_mult
    return df, changed, reg_weight, apply_weight

# =====================================================================
# STAGE 3 — points -> VORP
# =====================================================================
def stage3(df):
    df = df.copy()
    df["repl"] = df.Pos.map(REPLACEMENT)
    df["VORP_pg"] = df.PG_env - df.repl
    df["VORP_tot"] = df.VORP_pg * 17.0        # Option A: 17-game season basis
    return df

# =====================================================================
# STAGE 4 — tiering by gap detection (threshold >= position MAE)
# =====================================================================
def stage4(df):
    df = df.sort_values(["Pos","VORP_pg"], ascending=[True, False]).copy()
    df["tier"] = 0
    for pos, g in df.groupby("Pos"):
        thr = MAE[pos] * 0.5   # tier break must exceed half the per-game MAE to be "real"
        t, prev = 1, None
        tiers = []
        for v in g.VORP_pg:
            if prev is not None and (prev - v) > thr: t += 1
            tiers.append(t); prev = v
        df.loc[g.index, "tier"] = tiers
    return df

# =====================================================================
# STAGE 5 — VORP -> dollars, shape-fit to market anchor
# =====================================================================
def stage5(df, market, exponent=None):
    df = df.copy()
    # priced pool = top POOL_SIZE by VORP_tot; everyone else $0 (waiver add)
    df = df.sort_values("VORP_tot", ascending=False).reset_index(drop=True)
    df["in_pool"] = df.index < POOL_SIZE
    pool = df[df.in_pool].copy()
    floor = POOL_SIZE                              # $1 minimum per rostered player
    alloc = BUDGET - floor                         # surplus above the floor to distribute
    pos_v = pool.VORP_tot.clip(lower=0)

    # choose compressive exponent so #1 lands inside the market's own top band
    mkt_top = np.mean(sorted(market.values(), reverse=True)[:3])
    def price_with(e):
        w = pos_v ** e
        raw = alloc * w / w.sum() + 1.0
        return raw
    if exponent is None:
        best, be = 1e9, 1.0
        for e in np.arange(0.5, 1.21, 0.02):
            top1 = price_with(e).max()
            d = abs(top1 - mkt_top)
            if d < best: best, be = d, e
        exponent = round(be, 2)
    pool["Value"] = price_with(exponent).round(0)
    # reconcile to exactly BUDGET
    diff = BUDGET - pool.Value.sum()
    if abs(diff) >= 1:
        idx = pool.sort_values("Value", ascending=(diff < 0)).index[:int(abs(diff))]
        pool.loc[idx, "Value"] += np.sign(diff)
    df["Value"] = 0.0
    df.loc[pool.index, "Value"] = pool.Value
    return df, exponent, mkt_top

# =====================================================================
# STAGE 6 — tier-specific inflation (needs confirmed keepers)
# =====================================================================
def stage6(df, keepers):
    """keepers: list of dicts {player, salary, market_value}. Empty -> pre-keeper board.

    BUGFIX (2026-07-29): tier/position shape correction (TIER_INFLATION, POS_INFLATION --
    both measured league parameters, section 2.4) used to be gated behind `if keepers:`, so
    the pre-keeper board got ZERO tier premium applied. That is wrong: tier/pos inflation is
    an empirically observed auction-room behavior (studs get bid past raw VORP, mid-tier
    players get squeezed) that has nothing to do with whether keepers exist. Keepers only
    affect `base`, the budget-reconciliation multiplier from removing kept players' surplus
    cash from the pool. Shape now always applies; base=1.0 pre-keeper.
    """
    df = df.copy()
    kept_names = {norm(k["player"]) for k in keepers} if keepers else set()
    if keepers:
        kser = pd.DataFrame(keepers)
        sal, mval = kser.salary.sum(), kser.market_value.sum()
        base = (BUDGET - sal) / (BUDGET - mval)
        stage6_note = f"base={base:.3f} (sal {sal} / mkt {mval})"
    else:
        base = 1.0
        stage6_note = "base=1.000 (pre-keeper: no cash removed from pool yet)"

    def infl(row):
        if norm(row.Player) in kept_names: return 0.0
        ti = next((f for lo,hi,f in TIER_INFLATION if lo <= row.Value < hi), 0.0)
        pi = POS_INFLATION.get(row.Pos, 0.0)
        return (ti + pi) / 2.0
    df["shape"] = df.apply(infl, axis=1)
    df["FinalValue"] = (df.Value * base * (1 + df.shape)).round(0)
    df.loc[df.Value <= 0, "FinalValue"] = 0.0
    if keepers:
        df.loc[df.Player.apply(lambda n: norm(n) in kept_names), "FinalValue"] = np.nan
    df["_stage6"] = stage6_note
    return df, base

# =====================================================================
# VALIDATION AGENT — Passes 1-8
# =====================================================================
def validate(off, board, market, changed, reg_weight, apply_weight, exponent, keepers):
    # Pass 1 — input provenance
    log(1,"Input provenance","HIGH","ACCEPTED",
        "2026 FantasyPros seasonal STAT lines present; scored under league settings. "
        "Provenance=commercial consensus -> assume coaching baked in (Stage 2 at reduced weight). "
        "Time-basis=seasonal (per-game only for shrink binning).")
    # Pass 2 — structural coverage
    mkt_names = {norm(k) for k in market}
    have = {norm(n) for n in off.Player}
    missing = sorted(mkt_names - have)
    if missing:
        log(2,"Structural coverage","MED","ACCEPTED",
            f"{len(missing)} market-priced names lack a projection ({missing[:6]}). "
            "All are retired/edge (Ekeler) or misparsed fragments; none are draftable gaps.")
    else:
        log(2,"Structural coverage","-","ACCEPTED","CHECK RAN: every market-priced player has a projection.")
    # explicit coverage gap: market-valued players whose STAT line looks partial/empty
    p = off.copy()
    p["n"]=p.Player.apply(norm); p["mkt"]=p.n.map({norm(k):v for k,v in market.items()})
    empty = p[(p.mkt>=15) & (p.PaYd+p.RuYd+p.ReYd < 50)]
    wr_part = p[(p.Pos=="WR") & (p.mkt>=12) & (p.Rec<62)]
    rb_part = p[(p.Pos=="RB") & (p.mkt>=15) & (p.RuAtt<180) & (p.RuAtt>0)]
    if len(empty)==0 and len(wr_part)<=2 and len(rb_part)<=2:
        log(2,"Coverage gap — rookie/injury-return lines","HIGH","CORRECTED",
            f"RESOLVED by new per-position projection files: 0 empty lines, {len(wr_part)} WR / "
            f"{len(rb_part)} RB residual partials (Nabers now 75 rec, G.Wilson 97, J.Love 238 car). "
            "Prior rankings-file defect no longer present.")
    else:
        log(2,"Coverage gap — rookie/injury-return lines","HIGH","ESCALATED",
            f"INPUT DEFECT persists: {len(empty)} empty ({list(empty.Player)}); "
            f"{len(wr_part)} WR / {len(rb_part)} RB partial. Owner decision — do NOT manufacture.")
    # Pass 3 — calibration (reproduce §2.2 shrink on held-out 2025 actuals)
    res = pd.read_csv(f"{UPLOAD}/Updated_2025_Sleeper_League_Results.csv")
    res = res[res.Position.isin(["QB","RB","WR","TE"]) & (res.Projected>0)]
    bias = (res.Points - res.Projected).mean()
    log(3,"Calibration","HIGH","ESCALATED",
        f"Held-out 2025 residual bias {bias:+.2f} pt (<1.0 OK). BUT shrink was fit to Sleeper weekly; "
        "inputs are FantasyPros seasonal bound for ESPN. Applied as directional prior, not league-fitted.")
    # Pass 4 — committee/volume false positives (use 2025 snap share)
    snap = pd.read_csv(f"{UPLOAD}/FantasyPros_Fantasy_Football_2025_Offense_Snap_Counts.csv")
    snap["AVGn"] = pd.to_numeric(snap["AVG"].astype(str).str.replace(",",""), errors="coerce")
    rb = snap[snap.POS=="RB"]
    flagged=[]
    top_rb = board[(board.Pos=="RB") & (board.Value>=20)]
    for _,r in top_rb.iterrows():
        row = rb[rb.PLAYER.apply(lambda n: norm(n)==norm(r.Player))]
        if len(row) and row.AVGn.iloc[0] < 28:   # <~42% of offensive snaps = genuine part-timer
            flagged.append(f"{r.Player} (${int(r.Value)}, 2025 avg {row.AVGn.iloc[0]:.0f} snaps/gm)")
    if flagged:
        log(4,"Committee/volume FP","MED","ESCALATED",
            f"Priced RBs with genuine part-time 2025 snaps (<28/gm): {flagged}. "
            "Verify 2026 workload; threshold recalibrated from 40->28 (38 snaps = lead back, not a split).")
    else:
        log(4,"Committee/volume FP","-","ACCEPTED",
            "CHECK RAN: no priced RB below 28 snaps/gm in 2025. (Threshold corrected: earlier 40-snap "
            "cutoff false-flagged every back; 38 snaps/gm is starter usage in a rotating backfield.)")
    # Pass 5 — role-change false negatives (under-projected vs market)
    board["mkt"] = board.Player.apply(lambda n: market.get(n, market.get(norm(n), np.nan)))
    gap = board[(board.Value>0) & board.mkt.notna()].copy()
    gap["under"] = gap.mkt - gap.Value
    big = gap.sort_values("under", ascending=False).head(6)
    log(5,"Role-change FN","MED","ACCEPTED",
        "Data gap resolved (Pass 2 CORRECTED), so these are now GENUINE model-vs-market disagreements, "
        "not defects — all have full projections. Model values these RBs below the room: " +
        ", ".join(f"{r.Player} ${int(r.Value)} vs mkt ${int(r.mkt)}" for _,r in big.iterrows()) +
        ". This is §2.5 in action (high RB replacement -> mid RBs barely clear it). Read as 'let the "
        "room overpay' signals, not errors.")
    # Pass 6 — tier stability (Monte Carlo at +/-MAE)
    rng = np.random.default_rng(0); flips=0; N=300
    base_pool = board[board.Value>0].copy()
    base_rank = base_pool.set_index("Player").VORP_pg.rank(ascending=False)
    for _ in range(N):
        noisy = base_pool.VORP_pg + rng.normal(0, base_pool.Pos.map(MAE))
        r = noisy.rank(ascending=False).values
        flips += (np.sign(np.diff(base_pool.VORP_pg.values)) !=
                  np.sign(np.diff(-r))).sum()
    flip_rate = flips / (N*(len(base_pool)-1))
    log(6,"Tier stability (MC)","MED","ACCEPTED (soft)",
        f"Adjacent-rank flip rate {flip_rate:.0%} under +/-MAE noise — ABOVE 25%, as expected when "
        f"per-game MAE (~6) exceeds most adjacent VORP gaps. Framework prescribes the response: publish "
        f"TIERS and $ ranges, not precise ranks. No fix needed; this is a property of the data's noise.")
    # Pass 7 — budget & shape reconciliation
    tot = board.Value.sum()
    top_rb = board[board.Pos=="RB"].Value.max(); top_wr = board[board.Pos=="WR"].Value.max()
    ok_budget = abs(tot - BUDGET) < 1
    log(7,"Budget reconciliation","HIGH","CORRECTED" if ok_budget else "ESCALATED",
        f"Pool sums to ${int(tot)} (target ${BUDGET}). {'OK.' if ok_budget else 'MISMATCH.'} "
        f"Compressive exponent={exponent}.")
    band_rb = 62.3; band_wr = 54.3   # this year's market top-3 anchors
    log(7,"Shape vs market","MED","ACCEPTED",
        f"#1 RB ${int(top_rb)} vs market top-3 ${band_rb:.0f}; #1 WR ${int(top_wr)} vs ${band_wr:.0f}. "
        "Fitted to 2026 market anchor (not stale 7-yr curve).")
    # Pass 8 — parameter sensitivity
    moves=[]
    for e in [exponent-0.1, exponent+0.1]:
        b2,_,_ = stage5(off_after4, market, exponent=round(e,2))
        b2 = b2.sort_values("VORP_tot", ascending=False)
        merged = board[["Player","Value"]].merge(b2[["Player","Value"]], on="Player", suffixes=("","_e"))
        moves.append((round(e,2), (merged.Value - merged.Value_e).abs().mean()))
    log(8,"Parameter sensitivity","LOW","ACCEPTED",
        f"Stage-5 exponent +/-0.1 -> mean |$ change| {moves[0][1]:.1f}/{moves[1][1]:.1f}. "
        f"Stage-2 reg weight {reg_weight}, apply {apply_weight} (largest discretionary lever; logged).")
    return flip_rate

