if __name__ == "__main__":
    off, market = load_projections()
    off = stage1(off)
    off, changed, rw, aw = stage2(off)
    off = stage3(off)
    off = stage4(off)
    off_after4 = off.copy()
    board, exponent, mkt_top = stage5(off, market)
    keepers = []   # <-- owner flags 2/team here (24 total); empty = pre-keeper board
    board, base = stage6(board, keepers)

    validate(off, board, market, changed, rw, aw, exponent, keepers, off_after4)

