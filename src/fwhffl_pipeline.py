"""
FWHFFL 2026 Draft Kit — Path B pipeline (Stages 1-6 + Validation Passes 1-8)
=============================================================================
Adapted from src/fwhffl_pipeline_original_reference.py to run against the files that
actually exist in ./data. See docs/KNOWN_GAPS.md for the full list of what's missing
and why each guarded block below is guarded.

CHANGES vs. the reference script (do not lose track of these if you resync):
  1. Paths point at ./data (relative to repo root) instead of /mnt/user-data/uploads
     and /mnt/project.
  2. load_projections() reads the RB/WR/TE/QB files that actually exist
     (FantasyPros_Fantasy_Football_Projections_{RB1,WR1,TE1,QB2}.csv) instead of a
     combined FLX file and a differently-named QB file. Each file has a blank/junk
     second row (a stray header artifact) that is skipped on load.
  3. The market/cheat-sheet loader now treats cheatsheet3.csv correctly: it has NO
     dollar values (it's an ADP/ECR export, not an auction $ sheet — see
     docs/KNOWN_GAPS.md). Stage 5's exponent-fitting falls back to a hard-coded
     default and prints a warning instead of silently fitting against nothing.
  4. Stage 2 (team environment) is wrapped in a guard: NFL_Offensive_Analytics_2024_
     2025.xlsx is not in ./data, so Stage 2 no-ops (env_mult = 1.0 for everyone) and
     prints a clear warning rather than crashing or fabricating an environment signal.
  5. Validation Passes 3 and 4 are wrapped in guards for the same reason (their source
     files — held-out Sleeper actuals, 2025 snap counts — are also missing) and log an
     explicit "SKIPPED — missing input" finding instead of running against substitute
     data.
  6. Everything else (Stages 1, 3, 4, 5, 6, Passes 1/2/5/6/7/8) is unchanged logic from
     the reference script.
  7. BUGFIX (this adaptation, 2026-08-09): load_projections() parsed INT and FL columns
     from the projection files but never applied them in SeasProj -- the reference
     script has this same omission. League scoring (LEAGUE_RULES.md) charges -2 pts per
     interception thrown and an effective -2 pts per fumble lost (VALIDATED_PARAMETERS.md
     §Findings: reverse-engineered net of the manifesto's two stacking -1 rules).
     FantasyPros projects fumbles LOST (not total fumbles), so the -2 coefficient is
     applied directly per FL. Confirmed with the owner (Nic) before changing scoring
     output. See docs/DRAFT_KIT_FRAMEWORK.md for the corrected SeasProj formula.

Design decisions locked with the owner (unchanged from the reference script):
  - Games assumption = OPTION A: trust FantasyPros' seasonal blend as-is.
    Season total / 17 is used ONLY to bin players into per-game shrink bands.
  - Stage 1 shrink = directional prior (ESCALATED: FantasyPros seasonal -> ESPN, not
    league-fitted).
  - Auction values are GENERATED by the model; the market sheet (when one with real $
    values exists) is a Stage 5 shape anchor and Stage 6 pre-keeper baseline only —
    never a direct input.
  - Never manufacture projections. Never close a validation finding silently.
"""

import pandas as pd, numpy as np, re, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

# ----- measured league parameters (locked; see docs/VALIDATED_PARAMETERS.md) -----
REPLACEMENT = {"QB": 18.98, "RB": 11.13, "WR": 9.15, "TE": 10.65}      # §2.1 pts/game
MAE         = {"QB": 6.67,  "RB": 6.54,  "WR": 6.34,  "TE": 5.84}      # §2.2 mean abs error
SHRINK_BANDS = [                                                        # §2.2 (per-game bins)
    (0, 5, 1.345), (5, 10, 0.960), (10, 15, 0.965), (15, 20, 0.954), (20, 999, 0.942)
]
# §2.4 open-auction tier inflation (projected-$ tiers)
TIER_INFLATION = [(40, 999, 0.396), (25, 40, 0.288), (15, 25, -0.117),
                  (8, 15, -0.391), (3, 8, -0.485), (1, 3, -0.129)]
POS_INFLATION  = {"RB": 0.167, "QB": -0.203, "WR": -0.117, "TE": -0.231}  # §2.4 by position
BUDGET, TEAMS, ROSTER = 2400, 12, 13
POOL_SIZE = TEAMS * ROSTER            # 156 priced spots
REG_WEIGHT_DEFAULT = 0.6              # §3.2 tunable regression toward mean for new play callers
DEFAULT_EXPONENT = 0.86               # fallback when no real $ market sheet exists to fit against

FINDINGS = []  # (pass#, name, severity, disposition, detail)
def log(p, name, sev, disp, detail):
    FINDINGS.append((p, name, sev, disp, detail))

def norm(n):
    return re.sub(r"\s+(Jr\.|Sr\.|II|III|IV)$", "", str(n)).strip()

def _num(x):
    try: return float(str(x).replace(",", "").strip())
    except: return np.nan

# =====================================================================
# DATA LOAD + POSITION MAP
# =====================================================================
def load_projections():
    """Returns (off, market). `market` is {} if no real $ sheet is available —
    see docs/KNOWN_GAPS.md re: cheatsheet3.csv having no dollar values."""
    market = {}  # cheatsheet3.csv has no $ values; left empty deliberately, not guessed

    def load_pos(fname, cols, ru_first):
        path = os.path.join(DATA, fname)
        df = pd.read_csv(path, skiprows=[1])  # row 1 (index 1) is a stray blank artifact row
        df.columns = cols
        df = df[df.Player.astype(str).str.strip().str.len() > 1].copy()
        return df

    rb = load_pos("FantasyPros_Fantasy_Football_Projections_RB1.csv",
                   ["Player","Team","RuAtt","RuYd","RuTD","Rec","ReYd","ReTD","FL","FPTS"], True)
    wr = load_pos("FantasyPros_Fantasy_Football_Projections_WR1.csv",
                   ["Player","Team","Rec","ReYd","ReTD","RuAtt","RuYd","RuTD","FL","FPTS"], False)
    te = load_pos("FantasyPros_Fantasy_Football_Projections_TE1.csv",
                   ["Player","Team","Rec","ReYd","ReTD","FL","FPTS"], False)
    te["RuAtt"] = 0.0; te["RuYd"] = 0.0; te["RuTD"] = 0.0
    qb = load_pos("FantasyPros_Fantasy_Football_Projections_QB2.csv",
                   ["Player","Team","PaAtt","Cmp","PaYd","PaTD","INT","RuAtt","RuYd","RuTD","FL","FPTS"], False)
    qb["Rec"] = 0.0; qb["ReYd"] = 0.0; qb["ReTD"] = 0.0

    for d in (rb, wr, te, qb):
        for c in ["RuAtt","RuYd","RuTD","Rec","ReYd","ReTD","FL"]:
            d[c] = d[c].apply(_num)
    qb["PaYd"] = qb["PaYd"].apply(_num); qb["PaTD"] = qb["PaTD"].apply(_num)
    qb["INT"] = qb["INT"].apply(_num)

    rb["Pos"] = "RB"; wr["Pos"] = "WR"; te["Pos"] = "TE"; qb["Pos"] = "QB"
    for d in (rb, wr, te):
        d["PaYd"] = 0.0; d["PaTD"] = 0.0; d["INT"] = 0.0

    cols = ["Player","Team","Pos","PaYd","PaTD","INT","Rec","ReYd","ReTD","RuAtt","RuYd","RuTD","FL"]
    off = pd.concat([rb[cols], wr[cols], te[cols], qb[cols]], ignore_index=True)
    # Interceptions thrown (QB only) and fumbles lost (all positions) are both -2 pts
    # per league scoring (LEAGUE_RULES.md). FantasyPros projects fumbles LOST, not total
    # fumbles, so the -2 "effective" coefficient (VALIDATED_PARAMETERS.md's reverse-
    # engineered net of the manifesto's two stacking -1 rules) is applied per FL directly.
    off["SeasProj"] = (off.PaYd*.05 + off.PaTD*4 + off.INT*-2 + off.RuYd*.15 + off.RuTD*6
                       + off.Rec*.5 + off.ReYd*.15 + off.ReTD*6 + off.FL*-2)
    off["PG_raw"] = off.SeasProj / 17.0
    return off.reset_index(drop=True), market

# =====================================================================
# STAGE 1 — calibrate (shrink) + attach uncertainty band
# =====================================================================
def stage1(df):
    def shrink_for(pg):
        for lo, hi, s in SHRINK_BANDS:
            if lo <= pg < hi: return s
        return 1.0
    df = df.copy()
    df["shrink"] = df.PG_raw.apply(shrink_for)
    df.loc[df.PG_raw < 5, "shrink"] = 1.0  # never let the <5 inflation band touch real draft boards
    df["PG"] = df.PG_raw * df.shrink
    df["MAE"] = df.Pos.map(MAE)
    return df

# =====================================================================
# STAGE 2 — team environment (GUARDED: source workbook missing)
# =====================================================================
def stage2(df, reg_weight=REG_WEIGHT_DEFAULT, apply_weight=0.5):
    wb = os.path.join(DATA, "NFL_Offensive_Analytics_2024_2025.xlsx")
    df = df.copy()
    if not os.path.exists(wb):
        print("[Stage 2] WARNING: NFL_Offensive_Analytics_2024_2025.xlsx not in ./data — "
              "team-environment adjustment SKIPPED (env_mult=1.0 for all players). "
              "See docs/KNOWN_GAPS.md.")
        df["env_mult"] = 1.0
        df["PG_env"] = df.PG
        return df, set(), reg_weight, apply_weight

    cm = pd.read_excel(wb, sheet_name="Coach Map", header=2).dropna(subset=["Team"])
    changed = set(cm.loc[cm["Play Caller Change 2026"].astype(str).str.upper()
                         .str.startswith("YES"), "Team"])
    aa = pd.read_excel(wb, sheet_name="Advanced Analytics", header=2).dropna(subset=["Team"])
    a25 = aa[aa.Season == 2025][["Team","Points/Game"]].copy()
    lg = a25["Points/Game"].mean()
    a25["mult_raw"] = a25["Points/Game"] / lg
    a25["mult"] = a25.apply(
        lambda r: 1.0 + (r.mult_raw-1.0)*(1-reg_weight) if r.Team in changed else r.mult_raw, axis=1)
    a25["mult_applied"] = 1.0 + (a25["mult"]-1.0)*apply_weight
    mult = dict(zip(a25.Team, a25.mult_applied))
    df["env_mult"] = df.Team.map(mult).fillna(1.0)
    df["PG_env"] = df.PG * df.env_mult
    return df, changed, reg_weight, apply_weight

# =====================================================================
# STAGE 3 — points -> VORP
# =====================================================================
def stage3(df):
    df = df.copy()
    df["repl"] = df.Pos.map(REPLACEMENT)
    df["VORP_pg"] = df.PG_env - df.repl
    df["VORP_tot"] = df.VORP_pg * 17.0        # Option A: 17-game season basis
    return df

# =====================================================================
# STAGE 4 — tiering by gap detection (threshold >= position MAE)
# =====================================================================
def stage4(df):
    df = df.sort_values(["Pos","VORP_pg"], ascending=[True, False]).copy()
    df["tier"] = 0
    for pos, g in df.groupby("Pos"):
        thr = MAE[pos] * 0.5
        t, prev = 1, None
        tiers = []
        for v in g.VORP_pg:
            if prev is not None and (prev - v) > thr: t += 1
            tiers.append(t); prev = v
        df.loc[g.index, "tier"] = tiers
    return df

# =====================================================================
# STAGE 5 — VORP -> dollars, shape-fit to market anchor (falls back if no market $)
# =====================================================================
def stage5(df, market, exponent=None):
    df = df.copy()
    df = df.sort_values("VORP_tot", ascending=False).reset_index(drop=True)
    df["in_pool"] = df.index < POOL_SIZE
    pool = df[df.in_pool].copy()
    floor = POOL_SIZE
    alloc = BUDGET - floor
    pos_v = pool.VORP_tot.clip(lower=0)

    def price_with(e):
        w = pos_v ** e
        raw = alloc * w / w.sum() + 1.0
        return raw

    mkt_top = None
    if exponent is None:
        if market:
            mkt_top = np.mean(sorted(market.values(), reverse=True)[:3])
            best, be = 1e9, 1.0
            for e in np.arange(0.5, 1.21, 0.02):
                top1 = price_with(e).max()
                d = abs(top1 - mkt_top)
                if d < best: best, be = d, e
            exponent = round(be, 2)
        else:
            print(f"[Stage 5] WARNING: no $-valued market sheet available — using default "
                  f"exponent {DEFAULT_EXPONENT} instead of fitting to a market anchor. "
                  f"See docs/KNOWN_GAPS.md.")
            exponent = DEFAULT_EXPONENT

    pool["Value"] = price_with(exponent).round(0)
    diff = BUDGET - pool.Value.sum()
    if abs(diff) >= 1:
        idx = pool.sort_values("Value", ascending=(diff < 0)).index[:int(abs(diff))]
        pool.loc[idx, "Value"] += np.sign(diff)
    df["Value"] = 0.0
    df.loc[pool.index, "Value"] = pool.Value
    return df, exponent, mkt_top

# =====================================================================
# STAGE 6 — tier-specific inflation (needs confirmed keepers)
# =====================================================================
def stage6(df, keepers):
    """keepers: list of dicts {player, salary, market_value}. Empty -> pre-keeper board.

    Tier/position shape (TIER_INFLATION, POS_INFLATION) always applies — it's an
    auction-room behavior pattern independent of whether keepers exist. Keepers only
    affect `base`, the budget-reconciliation multiplier from removing kept players'
    surplus cash from the pool. base=1.0 pre-keeper.

    BUGFIX (this adaptation): the reference script names this column df["shape"],
    which collides with pandas' built-in DataFrame.shape attribute — `df.shape` then
    silently returns the (rows, cols) tuple instead of the column, and the FinalValue
    line raises a TypeError. Renamed to df["infl_pct"] here. If you ever resync this
    file against the reference script, keep this rename.
    """
    df = df.copy()
    kept_names = {norm(k["player"]) for k in keepers} if keepers else set()
    if keepers:
        kser = pd.DataFrame(keepers)
        sal, mval = kser.salary.sum(), kser.market_value.sum()
        base = (BUDGET - sal) / (BUDGET - mval)
        stage6_note = f"base={base:.3f} (sal {sal} / mkt {mval})"
    else:
        base = 1.0
        stage6_note = "base=1.000 (pre-keeper: no cash removed from pool yet — NOT FINAL, " \
                       "see CLAUDE.md rule 4)"

    def infl(row):
        if norm(row.Player) in kept_names: return 0.0
        ti = next((f for lo,hi,f in TIER_INFLATION if lo <= row.Value < hi), 0.0)
        pi = POS_INFLATION.get(row.Pos, 0.0)
        return (ti + pi) / 2.0
    df["infl_pct"] = df.apply(infl, axis=1)
    df["FinalValue"] = (df.Value * base * (1 + df.infl_pct)).round(0)
    df.loc[df.Value <= 0, "FinalValue"] = 0.0
    if keepers:
        df.loc[df.Player.apply(lambda n: norm(n) in kept_names), "FinalValue"] = np.nan
    df["_stage6"] = stage6_note
    return df, base

# =====================================================================
# VALIDATION AGENT — Passes 1-8
# =====================================================================
def validate(off, board, market, changed, reg_weight, apply_weight, exponent, keepers, off_after4):
    # Pass 1 — input provenance
    log(1,"Input provenance","HIGH","ACCEPTED",
        "2026 FantasyPros seasonal STAT lines present; scored under league settings. "
        "Provenance=commercial consensus -> assume coaching baked in (Stage 2 at reduced "
        "weight, when Stage 2 has its source workbook). Time-basis=seasonal (per-game only "
        "for shrink binning).")

    # Pass 2 — structural coverage (market sheet has no $ values here, so this degrades
    # to a name/format sanity check rather than a market-coverage check)
    if market:
        mkt_names = {norm(k) for k in market}
        have = {norm(n) for n in off.Player}
        missing = sorted(mkt_names - have)
        if missing:
            log(2,"Structural coverage","MED","ACCEPTED",
                f"{len(missing)} market-priced names lack a projection ({missing[:6]}).")
        else:
            log(2,"Structural coverage","-","ACCEPTED","CHECK RAN: every market-priced player has a projection.")
    else:
        log(2,"Structural coverage","MED","ESCALATED",
            "SKIPPED — no $-valued market sheet available in ./data (cheatsheet3.csv has no "
            "dollar values). Cannot check board coverage against a real market. See docs/KNOWN_GAPS.md.")

    p = off.copy()
    p["n"] = p.Player.apply(norm)
    empty = p[(p.PaYd+p.RuYd+p.ReYd < 50) & (p.Pos != "QB")]
    wr_part = p[(p.Pos=="WR") & (p.Rec<10)]
    rb_part = p[(p.Pos=="RB") & (p.RuAtt<20) & (p.RuAtt>0)]
    log(2,"Coverage gap — rookie/injury-return lines","MED","ACCEPTED",
        f"{len(empty)} near-empty non-QB lines, {len(wr_part)} very-low-target WR, "
        f"{len(rb_part)} very-low-carry RB in the raw projection pool. Expected tail noise "
        f"for a 396/573/363-row unfiltered projection file; not flagged as a defect unless "
        f"a specific rostered/market-relevant name shows up empty.")

    # Pass 3 — calibration (GUARDED: held-out actuals file missing)
    sleeper_path = os.path.join(DATA, "Updated_2025_Sleeper_League_Results.csv")
    if os.path.exists(sleeper_path):
        res = pd.read_csv(sleeper_path)
        res = res[res.Position.isin(["QB","RB","WR","TE"]) & (res.Projected>0)]
        bias = (res.Points - res.Projected).mean()
        log(3,"Calibration","HIGH","ESCALATED",
            f"Held-out 2025 residual bias {bias:+.2f} pt. Shrink was fit to Sleeper weekly; "
            "inputs are FantasyPros seasonal bound for ESPN. Applied as directional prior.")
    else:
        log(3,"Calibration","HIGH","ESCALATED",
            "SKIPPED — Updated_2025_Sleeper_League_Results.csv not in ./data. Cannot verify "
            "Stage 1 shrink bias against held-out actuals. Shrink bands remain an unverified "
            "directional prior. See docs/KNOWN_GAPS.md.")

    # Pass 4 — committee/volume false positives (GUARDED: snap-count file missing)
    snap_path = os.path.join(DATA, "FantasyPros_Fantasy_Football_2025_Offense_Snap_Counts.csv")
    if os.path.exists(snap_path):
        snap = pd.read_csv(snap_path)
        snap["AVGn"] = pd.to_numeric(snap["AVG"].astype(str).str.replace(",",""), errors="coerce")
        rb = snap[snap.POS=="RB"]
        flagged=[]
        top_rb = board[(board.Pos=="RB") & (board.Value>=20)]
        for _,r in top_rb.iterrows():
            row = rb[rb.PLAYER.apply(lambda n: norm(n)==norm(r.Player))]
            if len(row) and row.AVGn.iloc[0] < 28:
                flagged.append(f"{r.Player} (${int(r.Value)}, 2025 avg {row.AVGn.iloc[0]:.0f} snaps/gm)")
        if flagged:
            log(4,"Committee/volume FP","MED","ESCALATED",
                f"Priced RBs with genuine part-time 2025 snaps (<28/gm): {flagged}.")
        else:
            log(4,"Committee/volume FP","-","ACCEPTED","CHECK RAN: no priced RB below 28 snaps/gm.")
    else:
        log(4,"Committee/volume FP","MED","ESCALATED",
            "SKIPPED — FantasyPros_Fantasy_Football_2025_Offense_Snap_Counts.csv not in ./data. "
            "Cannot check priced RBs for false-positive committee/volume roles. See docs/KNOWN_GAPS.md.")

    # Pass 5 — role-change false negatives (only meaningful with a real market sheet)
    if market:
        board["mkt"] = board.Player.apply(lambda n: market.get(n, market.get(norm(n), np.nan)))
        gap = board[(board.Value>0) & board.mkt.notna()].copy()
        gap["under"] = gap.mkt - gap.Value
        big = gap.sort_values("under", ascending=False).head(6)
        log(5,"Role-change FN","MED","ACCEPTED",
            "Model values these players below the (real $) market: " +
            ", ".join(f"{r.Player} ${int(r.Value)} vs mkt ${int(r.mkt)}" for _,r in big.iterrows()))
    else:
        log(5,"Role-change FN","MED","ESCALATED",
            "SKIPPED — no $-valued market sheet to compare against. See docs/KNOWN_GAPS.md.")

    # Pass 6 — tier stability (Monte Carlo at +/-MAE)
    rng = np.random.default_rng(0); flips=0; N=300
    base_pool = board[board.Value>0].copy()
    for _ in range(N):
        noisy = base_pool.VORP_pg + rng.normal(0, base_pool.Pos.map(MAE))
        r = noisy.rank(ascending=False).values
        flips += (np.sign(np.diff(base_pool.VORP_pg.values)) !=
                  np.sign(np.diff(-r))).sum()
    flip_rate = flips / (N*(len(base_pool)-1))
    log(6,"Tier stability (MC)","MED","ACCEPTED (soft)",
        f"Adjacent-rank flip rate {flip_rate:.0%} under +/-MAE noise. Framework prescribes "
        f"publishing TIERS and $ ranges, not precise ranks, whenever this is elevated.")

    # Pass 7 — budget & shape reconciliation
    tot = board.Value.sum()
    top_rb = board[board.Pos=="RB"].Value.max(); top_wr = board[board.Pos=="WR"].Value.max()
    ok_budget = abs(tot - BUDGET) < 1
    log(7,"Budget reconciliation","HIGH","CORRECTED" if ok_budget else "ESCALATED",
        f"Pool sums to ${int(tot)} (target ${BUDGET}). {'OK.' if ok_budget else 'MISMATCH.'} "
        f"Compressive exponent={exponent}.")
    if market:
        mkt_top3 = np.mean(sorted(market.values(), reverse=True)[:3])
        log(7,"Shape vs market","MED","ACCEPTED",
            f"#1 RB ${int(top_rb)} vs market top-3 ${mkt_top3:.0f}; #1 WR ${int(top_wr)}.")
    else:
        log(7,"Shape vs market","MED","ESCALATED",
            f"No real market $ sheet to compare against. #1 RB ${int(top_rb)}, #1 WR ${int(top_wr)} "
            f"are model-only, unanchored to a market shape check.")

    # Pass 8 — parameter sensitivity
    moves=[]
    for e in [exponent-0.1, exponent+0.1]:
        b2, _, _ = stage5(off_after4, market, exponent=round(e,2))
        merged = board[["Player","Value"]].merge(b2[["Player","Value"]], on="Player", suffixes=("","_e"))
        moves.append((round(e,2), (merged.Value - merged.Value_e).abs().mean()))
    log(8,"Parameter sensitivity","LOW","ACCEPTED",
        f"Stage-5 exponent +/-0.1 -> mean |$ change| {moves[0][1]:.1f}/{moves[1][1]:.1f}. "
        f"Stage-2 reg weight {reg_weight}, apply {apply_weight} (largest discretionary lever).")
    return flip_rate

